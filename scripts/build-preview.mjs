// Bundles the Markdown preview runtime (markdown-it + highlight.js + our renderer) into a
// TS module exporting a string, so the WebView works fully offline with no asset loading.
// Usage: node scripts/build-preview.mjs [--check]
import { build } from 'esbuild';
import { readFileSync, writeFileSync } from 'node:fs';

const out = 'src/features/markdown/preview/previewBundle.generated.ts';
const result = await build({
  entryPoints: ['src/features/markdown/preview/webEntry.ts'],
  bundle: true,
  minify: true,
  format: 'iife',
  target: ['chrome80'],
  write: false,
  legalComments: 'none',
});
const js = result.outputFiles[0].text;
const content =
  '// GENERATED by scripts/build-preview.mjs — do not edit. Run `npm run build:preview`.\n' +
  `export const PREVIEW_JS = ${JSON.stringify(js)};\n`;

if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(out, 'utf8');
  } catch {}
  if (current !== content) {
    console.error(`${out} is stale. Run: npm run build:preview`);
    process.exit(1);
  }
  console.log('preview bundle up to date');
} else {
  writeFileSync(out, content);
  console.log(`wrote ${out} (${(js.length / 1024).toFixed(0)} KB)`);
}
